#!/usr/bin/env python3
"""Render Convergence device telemetry artifacts (Phase 10).

From convergence.yaml (or targets YAML) produce:
  - Prometheus scrape job fragment (job device_snmp, managed-section ready)
  - snmp_exporter config (auths + vendor modules with ifDescr/ifName lookups)
  - Device-side SNMP/syslog config checklist (markdown)

Usage:
  python3 scripts/render-convergence-telemetry.py \\
    --config config/convergence.example.yaml \\
    --out-scrape /tmp/device_snmp_scrape.yml \\
    --out-snmp deploy/convergence/adapters/device-snmp/snmp.yml \\
    --out-checklist /tmp/device-config-checklist.md

  python3 scripts/render-convergence-telemetry.py \\
    --targets deploy/convergence/adapters/device-snmp/targets.example.yml \\
    --out-scrape -
"""

from __future__ import annotations

