def inject_managed_section(prometheus_yml: str, scrape_block: str) -> str:
    """Replace or append managed device_snmp section in prometheus.yml text."""
    begin = MARKER_BEGIN
    end = MARKER_END
    # scrape_block already includes markers when with_markers=True
    if begin in prometheus_yml and end in prometheus_yml:
        pre, rest = prometheus_yml.split(begin, 1)
        _, post = rest.split(end, 1)
        # drop leading newline duplication
        if post.startswith("\n"):
            post = post[1:]
        return pre + scrape_block.rstrip("\n") + "\n" + post

    # No markers: try replace existing un-marked device_snmp job, else append.
    lines = prometheus_yml.splitlines(keepends=True)
    out: list[str] = []
    i = 0
    replaced = False
    while i < len(lines):
        line = lines[i]
        # Detect start of device_snmp job (possibly with preceding comments)
        if (
            not replaced
            and line.lstrip().startswith("- job_name: device_snmp")
        ):
            # Walk back comment lines that are part of the job header
            # (already emitted? keep simple: drop from this line until next job or EOF)
            # Remove trailing comments immediately above that we already wrote?
            # Pop prior comment block about device_snmp if present
            while out and (
                out[-1].lstrip().startswith("#")
                or out[-1].strip() == ""
            ):
                # only strip comments that mention device_snmp / Campus
                prev = out[-1]
                if prev.strip() == "":
                    break
                if "device_snmp" in prev or "Campus/wired" in prev or "Phase 8" in prev:
                    out.pop()
                    continue
                break
            # skip until next top-level job or end of scrape_configs-ish
            i += 1
            while i < len(lines):
                nxt = lines[i]
                if nxt.startswith("  - job_name:"):
                    break
                if nxt.startswith("scrape_configs:") or (
                    nxt and not nxt[0].isspace() and not nxt.lstrip().startswith("#")
                ):
                    break
                i += 1
            # insert managed block (ensure indentation at job level)
            block = scrape_block
            if not block.endswith("\n"):
                block += "\n"
            out.append("\n" if out and not out[-1].endswith("\n") else "")
            # strip accidental double blank
            out.append(block if block.startswith("  ") or block.startswith("#") else block)
            replaced = True
            continue
        out.append(line)
        i += 1

    if not replaced:
        # Append before end of file
        text = "".join(out).rstrip() + "\n\n" + scrape_block.rstrip() + "\n"
        return text
    return "".join(out)


def render_suzieq_inventory(
    targets: list[dict],
    site: str = "home",
    namespace: str | None = None,
    ignore_known_hosts: bool = True,
    exclude_roles: list[str] | None = None,
) -> str:
    """Render a SuzieQ native inventory YAML from the convergence target list.

    Produces the same inventory that would otherwise be hand-authored for the
    SuzieQ poller. Credentials come from env vars at runtime — the rendered
    file contains ${SUZIEQ_DEVICE_USER} / ${SUZIEQ_DEVICE_PASSWORD} references
    that the deploy adapter resolves (just like SNMP_COMMUNITY for OTel).

    Args:
        targets: Normalized target dicts (name, ip, role, vendor, template).
        site: Site label — used as the SuzieQ namespace unless overridden.
        namespace: Override the namespace name (default: site).
        ignore_known_hosts: Set ignore-known-hosts on the default device entry.
        exclude_roles: Roles to skip (e.g. ["firewall"] for unsupported vendors).
    """
    ns = namespace or site
    exclude = set(r.lower() for r in (exclude_roles or []))

    filtered = [t for t in targets if t["role"] not in exclude]
    if not filtered:
        return f"# No targets after excluding roles: {sorted(exclude)}\n"

    # Map vendor to SuzieQ devtype
    vendor_to_devtype = {
        "cisco": "iosxe",
        "pfsense": None,  # unsupported
        "generic": None,
    }

    hosts = []
    for t in filtered:
        devtype = vendor_to_devtype.get(t["vendor"], None)
        if devtype is None:
            # Skip unsupported vendors rather than producing a bad inventory
            continue
        host_line = (
            f"ssh://${{SUZIEQ_DEVICE_USER}}:${{SUZIEQ_DEVICE_PASSWORD}}"
            f"@{t['ip']} devtype={devtype}"
        )
        hosts.append(f"      - url: {host_line}")

    if not hosts:
        return "# No SuzieQ-compatible targets found (unsupported vendors only)\n"

    lines = [
        "# Auto-generated by render-convergence-telemetry.py (Phase 12, T161)",
        f"# {len(hosts)} device(s), namespace={ns}",
        f"# Generated: {datetime.now(timezone.utc).strftime('%Y-%m-%d %H:%M UTC')}",
        "#",
        "# Credentials: set SUZIEQ_DEVICE_USER and SUZIEQ_DEVICE_PASSWORD in",
        "# deploy/convergence/.env — NEVER commit secrets to this file.",
        "",
        "sources:",
        f"  - name: {ns}",
        "    hosts:",
        *hosts,
        "",
        "devices:",
        "  - name: default",
    ]
    if ignore_known_hosts:
        lines.append("    ignore-known-hosts: true")
    lines += [
        "",
        "namespaces:",
        f"  - name: {ns}",
        f"    source: {ns}",
        "",
    ]
    return "\n".join(lines) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser(
        description="Render Convergence device telemetry (Phase 10)"
    )
    ap.add_argument("--config", type=Path, help="convergence.yaml")
    ap.add_argument("--targets", type=Path, help="targets YAML (targets: [...])")
    ap.add_argument("--site", default=None, help="override site label")
    ap.add_argument(
        "--modules-dir",
        type=Path,
        default=DEFAULT_MODULES_DIR,
        help="vendor module templates directory",
    )
    ap.add_argument(
        "--exporter",
        default="snmp-device-exporter:9116",
        help="Prometheus scrape replacement for snmp_exporter",
    )
    ap.add_argument(
        "--community",
        default=os.environ.get("SNMP_COMMUNITY", "public"),
        help="SNMPv2c community for snmp.yml (default SNMP_COMMUNITY or public)",
    )
    ap.add_argument("--poll-interval", default="60s")
    ap.add_argument(
        "--out-scrape",
        type=Path,
        help="write scrape fragment (use - for stdout via --print-scrape)",
    )
    ap.add_argument(
        "--out-snmp",
        type=Path,
        help="write full snmp_exporter snmp.yml",
    )
    ap.add_argument(
        "--out-checklist",
        type=Path,
        help="write device config checklist markdown",
    )
    ap.add_argument(
        "--out-suzieq",
        type=Path,
        help="write SuzieQ native inventory YAML (Phase 12, T161)",
    )
    ap.add_argument(
        "--suzieq-namespace",
        default=None,
        help="SuzieQ namespace name (default: site name)",
    )
    ap.add_argument(
        "--suzieq-exclude-roles",
        default="firewall",
        help="comma-separated roles to exclude from SuzieQ inventory (default: firewall)",
    )
    ap.add_argument(
        "--inject-prometheus",
        type=Path,
        help="read/write this prometheus.yml with managed section",
    )
    ap.add_argument(
        "--syslog-host",
        default=None,
        help="override syslog destination IP in checklist",
    )
    ap.add_argument(
        "--syslog-port",
        type=int,
        default=1514,
    )
    ap.add_argument(
        "--inject-otel",
        type=Path,
        help="read/write the OTel Collector config, replacing its managed sections "
             "(snmp receivers, per-device resource processors, metrics pipelines, "
             "and the syslog sender-IP → device_name map)",
    )
    ap.add_argument(
        "--otel-job",
        default="device_snmp",
        help="Prometheus job label the collector should claim (service.name). "
             "Use a distinct value (e.g. device_snmp_otel) to stage alongside an "
             "existing writer before cutting over.",
    )
    ap.add_argument(
        "--print-otel",
        action="store_true",
        help="print the OTel managed blocks to stdout",
    )
    ap.add_argument(
        "--print-scrape",
        action="store_true",
        help="print scrape fragment to stdout",
    )
    ap.add_argument(
        "--no-markers",
        action="store_true",
        help="omit BEGIN/END markers in scrape fragment",
    )
    args = ap.parse_args()

    if not args.config and not args.targets:
        ap.error("need --config or --targets")

    site = args.site or "home"
    poll = args.poll_interval
    targets: list[dict] = []

    if args.targets:
        doc = load_yaml(args.targets)
        targets = targets_from_file(doc)
        if doc.get("site"):
            site = str(doc["site"])
    if args.config:
        cfg = load_yaml(args.config)
        if not args.targets:
            targets = targets_from_convergence(cfg)
        if cfg.get("site") and not args.site:
            site = str(cfg["site"])
        snmp = (cfg.get("device_telemetry") or {}).get("snmp") or {}
        if snmp.get("poll_interval") and args.poll_interval == "60s":
            poll = str(snmp["poll_interval"])
        syslog = (cfg.get("device_telemetry") or {}).get("syslog") or {}
        listen = str(syslog.get("listen") or "")
        if listen and ":" in listen and args.syslog_port == 1514:
            try:
                args.syslog_port = int(listen.rsplit(":", 1)[-1])
            except ValueError:
                pass

    targets = sort_targets(targets)
    syslog_devices = syslog_devices_from_convergence(cfg) if args.config else []
    scrape = render_scrape(
        targets,
        site=site,
        exporter=args.exporter,
        poll_interval=poll,
        with_markers=not args.no_markers,
    )

    if args.print_scrape or (args.out_scrape and str(args.out_scrape) == "-"):
        sys.stdout.write(scrape if scrape.endswith("\n") else scrape + "\n")
    elif args.out_scrape:
        args.out_scrape.parent.mkdir(parents=True, exist_ok=True)
        args.out_scrape.write_text(
            scrape if scrape.endswith("\n") else scrape + "\n", encoding="utf-8"
        )
        print(f"Wrote scrape → {args.out_scrape} ({len(targets)} targets)", file=sys.stderr)

    if args.out_snmp:
        snmp_text = render_snmp_yml(
            targets,
            modules_dir=args.modules_dir,
            community=args.community,
        )
        args.out_snmp.parent.mkdir(parents=True, exist_ok=True)
        args.out_snmp.write_text(snmp_text, encoding="utf-8")
        print(f"Wrote snmp.yml → {args.out_snmp}", file=sys.stderr)

    if args.out_checklist:
        md = render_checklist(
            targets,
            site=site,
            syslog_host=args.syslog_host,
            syslog_port=args.syslog_port,
        )
        args.out_checklist.parent.mkdir(parents=True, exist_ok=True)
        args.out_checklist.write_text(md, encoding="utf-8")
        print(f"Wrote checklist → {args.out_checklist}", file=sys.stderr)

    if args.out_suzieq:
        exclude_roles = [
            r.strip() for r in (args.suzieq_exclude_roles or "").split(",") if r.strip()
        ]
        suzieq_inv = render_suzieq_inventory(
            targets,
            site=site,
            namespace=args.suzieq_namespace,
            ignore_known_hosts=True,
            exclude_roles=exclude_roles,
        )
        args.out_suzieq.parent.mkdir(parents=True, exist_ok=True)
        args.out_suzieq.write_text(suzieq_inv, encoding="utf-8")
        print(f"Wrote SuzieQ inventory → {args.out_suzieq}", file=sys.stderr)

    otel_blocks = {
        "receivers": render_otel_receivers(targets, poll_interval=poll),
        "processors": render_otel_processors(targets, site=site, job=args.otel_job),
        "pipelines": render_otel_pipelines(targets),
        "devicemap": render_otel_device_map(targets, syslog_devices=syslog_devices),
    }

    if args.print_otel:
        for key in ("receivers", "processors", "pipelines", "devicemap"):
            sys.stdout.write(otel_blocks[key])
            sys.stdout.write("\n")

    if args.inject_otel:
        src = args.inject_otel
        if not src.is_file():
            print(f"otel config not found: {src}", file=sys.stderr)
            return 1
        text = src.read_text(encoding="utf-8")
        try:
            for key in ("receivers", "processors", "pipelines", "devicemap"):
                text = inject_marked_block(text, otel_blocks[key], OTEL_MARKERS[key])
        except KeyError as exc:
            print(
                f"{exc}\nThe collector config must contain the managed markers. "
                "See deploy/convergence/otel/snmp-receivers.md.",
                file=sys.stderr,
            )
            return 1
        src.write_text(text, encoding="utf-8")
        print(
            f"Injected OTel managed sections → {src} "
            f"({len(targets)} device(s), job={args.otel_job})",
            file=sys.stderr,
        )

    if args.inject_prometheus:
        src = args.inject_prometheus
        if not src.is_file():
            print(f"prometheus.yml not found: {src}", file=sys.stderr)
            return 1
        original = src.read_text(encoding="utf-8")
        updated = inject_managed_section(original, scrape)
        src.write_text(updated, encoding="utf-8")
        print(f"Injected managed device_snmp section → {src}", file=sys.stderr)

    if not any(
        [
            args.out_scrape,
            args.out_snmp,
            args.out_checklist,
            args.out_suzieq,
            args.inject_prometheus,
            args.print_scrape,
            args.inject_otel,
            args.print_otel,
        ]
    ):
        # Default: print scrape
        sys.stdout.write(scrape if scrape.endswith("\n") else scrape + "\n")

    print(
        f"Rendered {len(targets)} target(s) site={site} "
        f"templates={sorted({t['template'] for t in targets}) or ['(none)']}",
        file=sys.stderr,
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
