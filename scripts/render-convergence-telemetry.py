import sys
from datetime import datetime, timezone
from pathlib import Path

try:
    import yaml  # type: ignore
except ImportError:
    print("PyYAML required: pip install pyyaml", file=sys.stderr)
    sys.exit(1)

REPO_ROOT = Path(__file__).resolve().parents[1]
DEFAULT_MODULES_DIR = (
    REPO_ROOT / "deploy/convergence/adapters/device-snmp/modules"
)
VALID_TEMPLATES = ("cisco", "pfsense", "generic")
ROLE_DEFAULT = "switch"
MARKER_BEGIN = "# BEGIN netclaw-convergence-device-snmp"
MARKER_END = "# END netclaw-convergence-device-snmp"

# OTel Collector managed sections (Phase 11 / T154). Three separate blocks because
# they live in different top-level keys of the collector config.
OTEL_MARKERS = {
    "receivers": (
        "  # BEGIN netclaw-convergence-otel-snmp-receivers",
        "  # END netclaw-convergence-otel-snmp-receivers",
    ),
    "processors": (
        "  # BEGIN netclaw-convergence-otel-snmp-processors",
        "  # END netclaw-convergence-otel-snmp-processors",
    ),
    "pipelines": (
        "    # BEGIN netclaw-convergence-otel-snmp-pipelines",
        "    # END netclaw-convergence-otel-snmp-pipelines",
    ),
    "devicemap": (
        "          # BEGIN netclaw-convergence-device-map",
        "          # END netclaw-convergence-device-map",
    ),
}

# OTel metric → OID map. Names are chosen so prometheusremotewrite emits exactly
# the metric names Convergence already uses (measured in T145): `By` + monotonic
# sum → _bytes_total, annotation units like {errors}/{state} are dropped. Changing
# a unit here silently renames a metric — see otel/snmp-receivers.md.
OTEL_IF_METRICS = [
    ("interface.octets.in", "1.3.6.1.2.1.31.1.1.1.6", "By", "sum"),
    ("interface.octets.out", "1.3.6.1.2.1.31.1.1.1.10", "By", "sum"),
    ("interface.errors.in", "1.3.6.1.2.1.2.2.1.14", "{errors}", "sum"),
    ("interface.errors.out", "1.3.6.1.2.1.2.2.1.20", "{errors}", "sum"),
    ("interface.status", "1.3.6.1.2.1.2.2.1.8", "{state}", "gauge"),
    ("interface.admin.status", "1.3.6.1.2.1.2.2.1.7", "{state}", "gauge"),
]
OID_IF_DESCR = "1.3.6.1.2.1.2.2.1.2"


def otel_receiver_key(target: dict) -> str:
    """Stable, YAML-safe receiver suffix derived from the device name."""
    safe = "".join(c if c.isalnum() else "_" for c in target["name"].lower())
    return safe.strip("_") or target["ip"].replace(".", "_")


def render_otel_receivers(
    targets: list[dict],
    *,
    poll_interval: str = "60s",
    community_env: str = "SNMP_COMMUNITY",
    with_markers: bool = True,
) -> str:
    begin, end = OTEL_MARKERS["receivers"]
    out: list[str] = []
    if with_markers:
        out.append(begin)
        out.append("  # Generated by scripts/render-convergence-telemetry.py — do not hand-edit.")
        out.append("  # Edit inventory in convergence.yaml, then re-run the apply script.")
    for i, tgt in enumerate(targets):
        key = otel_receiver_key(tgt)
        out.append(f"  snmp/{key}:")
        out.append(f"    collection_interval: {poll_interval}")
        # Stagger starts so N devices are not polled in the same instant.
        out.append(f"    initial_delay: {i * 5}s")
        out.append(f"    endpoint: udp://{tgt['ip']}:161")
        out.append("    version: v2c")
        out.append(f"    community: ${{env:{community_env}}}")
        out.append("    timeout: 30s")
        out.append("    resource_attributes:")
        out.append("      interface.name:")
        out.append(f"        oid: {OID_IF_DESCR}")
        out.append("    metrics:")
        for name, oid, unit, kind in OTEL_IF_METRICS:
            if name == "interface.admin.status":
                out.append("      # ifAdminStatus — with interface.status this separates")
                out.append("      # administratively-shut from link-failed.")
            out.append(f"      {name}:")
            out.append(f'        unit: "{unit}"' if unit.startswith("{") else f"        unit: {unit}")
            if kind == "sum":
                out.append("        sum: {value_type: int, aggregation: cumulative, monotonic: true}")
            else:
                out.append("        gauge: {value_type: int}")
            out.append("        column_oids:")
            out.append(f"          - oid: {oid}")
            out.append("            resource_attributes: [interface.name]")
    if with_markers:
        out.append(end)
    return "\n".join(out) + "\n"


def render_otel_processors(
    targets: list[dict],
    *,
    site: str = "home",
    job: str = "device_snmp",
    with_markers: bool = True,
) -> str:
    """Per-device resource processors.

    service.name → Prometheus `job`, service.instance.id → `instance`. Setting them
    is what lets the OTel path keep every selector that existed under
    snmp_exporter (FR-040).
    """
    begin, end = OTEL_MARKERS["processors"]
    out: list[str] = []
    if with_markers:
        out.append(begin)
        out.append("  # Generated — service.name becomes the Prometheus `job` label and")
        out.append("  # service.instance.id becomes `instance`, preserving existing selectors.")
    for tgt in targets:
        key = otel_receiver_key(tgt)
        out.append(f"  resource/{key}:")
        out.append("    attributes:")
        out.append(f"      - {{key: service.name,        value: {job}, action: upsert}}")
        out.append(f"      - {{key: service.instance.id, value: \"{tgt['ip']}\", action: upsert}}")
        out.append(f"      - {{key: device_name,         value: {tgt['name']}, action: upsert}}")
        out.append(f"      - {{key: role,                value: {tgt['role']}, action: upsert}}")
        out.append(f"      - {{key: vendor,              value: {tgt['vendor']}, action: upsert}}")
        out.append(f"      - {{key: site,                value: {site}, action: upsert}}")
    if with_markers:
        out.append(end)
    return "\n".join(out) + "\n"


def render_otel_pipelines(
    targets: list[dict],
    *,
    exporters: str = "prometheusremotewrite/prometheus, prometheusremotewrite/victoriametrics",
    with_markers: bool = True,
) -> str:
    begin, end = OTEL_MARKERS["pipelines"]
    out: list[str] = []
    if with_markers:
        out.append(begin)
    for tgt in targets:
        key = otel_receiver_key(tgt)
        out.append(f"    metrics/{key}:")
        out.append(f"      receivers: [snmp/{key}]")
        out.append(f"      processors: [memory_limiter, resource/{key}, batch]")
        out.append(f"      exporters: [{exporters}]")
    if with_markers:
        out.append(end)
    return "\n".join(out) + "\n"


def render_otel_device_map(
    targets: list[dict],
    *,
    syslog_devices: list[dict] | None = None,
    with_markers: bool = True,
) -> str:
    """OTTL statements mapping syslog sender IP → device_name.

    Sender IP beats the hostname inside the message: it is present on every
    datagram and cannot be shaped by message content.

    Covers the UNION of SNMP targets and syslog-only devices. Generating from SNMP
    targets alone silently dropped pfSense, a switch with no SNMP access, and the
    NetClaw host from this site's map — all of which send logs.
    """
    begin, end = OTEL_MARKERS["devicemap"]
    merged: dict[str, str] = {}
    for tgt in targets:
        merged[tgt["ip"]] = tgt["name"]
    for dev in syslog_devices or []:
        merged.setdefault(dev["ip"], dev["name"])
    out: list[str] = []
    if with_markers:
        out.append(begin)
        out.append("          # Generated — union of device_telemetry.snmp.targets and")
        out.append("          # device_telemetry.syslog.devices. Edit inventory, not this block.")
    width = max((len(n) for n in merged.values()), default=0)
    for ip, name in sorted(merged.items(), key=lambda kv: kv[1].lower()):
        pad = " " * (width - len(name))
        out.append(
            f'          - set(attributes["device_name"], "{name}"){pad}'
            f' where attributes["net.peer.ip"] == "{ip}"'
        )
    if with_markers:
        out.append(end)
    return "\n".join(out) + "\n"


def inject_marked_block(text: str, block: str, markers: tuple[str, str]) -> str:
    """Replace a BEGIN/END delimited region. Idempotent; raises if markers absent."""
    begin, end = markers
    if begin not in text or end not in text:
        raise KeyError(f"managed markers not found: {begin}")
    pre, rest = text.split(begin, 1)
    _, post = rest.split(end, 1)
    if post.startswith("\n"):
        post = post[1:]
    return pre + block.rstrip("\n") + "\n" + post


def load_yaml(path: Path) -> dict:
    return yaml.safe_load(path.read_text(encoding="utf-8")) or {}


def normalize_template(vendor: str | None, template: str | None) -> str:
    t = (template or vendor or "generic").strip().lower()
    if t in ("ios", "ios-xe", "catalyst", "nxos"):
        return "cisco"
    if t in ("pf", "pfsense-fw", "firewall-pfsense"):
        return "pfsense"
    if t not in VALID_TEMPLATES and t != "if_mib":
        return "generic"
    if t == "if_mib":
        return "generic"
    return t


def normalize_target(raw: dict) -> dict | None:
    ip = (raw.get("ip") or raw.get("address") or "").strip()
    if not ip:
        return None
    name = (raw.get("name") or ip).strip()
    role = (raw.get("role") or ROLE_DEFAULT).strip().lower()
    vendor = (raw.get("vendor") or "").strip().lower() or None
    template = normalize_template(vendor, raw.get("template"))
    if not vendor:
        vendor = template
    return {
        "name": name,
        "ip": ip,
        "role": role,
        "vendor": vendor,
        "template": template,
    }


def syslog_devices_from_convergence(cfg: dict) -> list[dict]:
    """Devices that send syslog but are not SNMP targets.

    The sender-IP → device_name map must cover every log source, not just the
    SNMP inventory. Missing entries are not fatal — device_name falls back to the
    message hostname and then the raw IP — but the label is then inconsistent with
    the SNMP inventory, which makes cross-signal correlation harder.
    """
    syslog = (cfg.get("device_telemetry") or {}).get("syslog") or {}
    out: list[dict] = []
    for d in syslog.get("devices") or []:
        ip = (d.get("ip") or d.get("address") or "").strip()
        name = (d.get("name") or "").strip()
        if ip and name:
            out.append({"name": name, "ip": ip})
    return out


def targets_from_convergence(cfg: dict) -> list[dict]:
    dt = (cfg.get("device_telemetry") or {}).get("snmp") or {}
    # Include targets even when enabled=false so dry-render still works;
    # apply decides whether to enable the profile.
    out: list[dict] = []
    for t in dt.get("targets") or []:
        n = normalize_target(t)
        if n:
            out.append(n)
    return out


def targets_from_file(doc: dict) -> list[dict]:
    out: list[dict] = []
    for t in doc.get("targets") or []:
        n = normalize_target(t)
        if n:
            out.append(n)
    return out


def sort_targets(targets: list[dict]) -> list[dict]:
    return sorted(targets, key=lambda t: (t["name"].lower(), t["ip"]))


def render_scrape(
    targets: list[dict],
    *,
    site: str = "home",
    exporter: str = "snmp-device-exporter:9116",
    poll_interval: str = "60s",
    with_markers: bool = True,
) -> str:
    """Render device_snmp job. Module per target via snmp_module label + relabel."""
    lines: list[str] = []
    if with_markers:
        lines.append(MARKER_BEGIN)
    lines.extend(
        [
            "  # Generated by scripts/render-convergence-telemetry.py — Phase 10",
            "  - job_name: device_snmp",
            f"    scrape_interval: {poll_interval}",
            "    metrics_path: /snmp",
            "    params:",
            "      module: [generic]",
            "      auth: [public_v2]",
            "    static_configs:",
        ]
    )
    if not targets:
        lines.append(
            "      []  # no targets — set device_telemetry.snmp.targets in convergence.yaml"
        )
    for t in targets:
        lines.append(f'      - targets: ["{t["ip"]}"]')
        lines.append("        labels:")
        lines.append(f"          site: {site}")
        lines.append(f"          device_name: {t['name']}")
        lines.append(f"          role: {t['role']}")
        lines.append(f"          vendor: {t['vendor']}")
        lines.append(f"          snmp_module: {t['template']}")
    lines.extend(
        [
            "    relabel_configs:",
            "      - source_labels: [__address__]",
            "        target_label: __param_target",
            "      - source_labels: [__param_target]",
            "        target_label: instance",
            "      - source_labels: [snmp_module]",
            "        target_label: __param_module",
            "      - target_label: __address__",
            f"        replacement: {exporter}",
        ]
    )
    if with_markers:
        lines.append(MARKER_END)
    lines.append("")
    return "\n".join(lines)


def load_module_body(modules_dir: Path, template_id: str) -> dict:
    path = modules_dir / f"{template_id}.yml"
    if not path.is_file():
        # Fall back to generic
        path = modules_dir / "generic.yml"
    if not path.is_file():
        raise FileNotFoundError(f"Missing SNMP module template: {path}")
    body = load_yaml(path)
    if not isinstance(body, dict):
        raise ValueError(f"Module {path} must be a mapping (walk/metrics)")
    return body


def render_snmp_yml(
    targets: list[dict],
    *,
    modules_dir: Path,
    community: str = "public",
    include_if_mib_alias: bool = True,
) -> str:
    needed = sorted({t["template"] for t in targets} | set(VALID_TEMPLATES))
    # Always ship all three vendor modules so apply is stable; if_mib alias optional.
    modules: dict[str, dict] = {}
    for tid in VALID_TEMPLATES:
        modules[tid] = load_module_body(modules_dir, tid)
    if include_if_mib_alias:
        modules["if_mib"] = load_module_body(modules_dir, "if_mib")

    doc = {
        "auths": {
            "public_v2": {
                "community": community,
                "version": 2,
            }
        },
        "modules": modules,
    }
    header = (
        "# Generated by scripts/render-convergence-telemetry.py — Phase 10\n"
        f"# templates_in_use: {', '.join(needed) if targets else '(none)'}\n"
        "# Community from SNMP_COMMUNITY env at apply time — do not commit real secrets.\n"
        "# snmp_exporter v0.26+ auth-split; per-metric ifDescr/ifName lookups.\n\n"
    )
    body = yaml.dump(
        doc,
        default_flow_style=False,
        sort_keys=False,
        allow_unicode=True,
        width=100,
    )
    return header + body


def detect_syslog_host() -> str:
    # Prefer primary outbound interface IP; fall back to hostname.
    try:
        s = socket.socket(socket.AF_INET, socket.SOCK_DGRAM)
        s.connect(("8.8.8.8", 80))
        ip = s.getsockname()[0]
        s.close()
        return ip
    except OSError:
        try:
            return socket.gethostbyname(socket.gethostname())
        except OSError:
            return "<convergence-host-ip>"


